/**
 * Move the sabha calendar from generated documents to a rule with exceptions.
 *
 * WHAT CHANGED UNDERNEATH
 * -----------------------
 * `settings/sabhaRecurrence` used to be a template that MATERIALISED one
 * `events/{date}` document per occurrence out to a horizon. Now the rule IS the
 * schedule and `events/{date}` documents are only exceptions to it: an edited
 * week, a cancelled week, or a one-off on a date the rule does not cover.
 *
 * So every existing future document has to be told which of those it is. Left
 * alone they default to `kind: 'override'` (the conservative reading), and an
 * override on a date the rule does not cover is INERT — which would silently
 * remove a gathering the manager can currently see.
 *
 * THE RULE THIS FOLLOWS: PRESERVE TODAY'S BEHAVIOUR
 * ------------------------------------------------
 * A migration that changes what the app does is not a migration. For each future
 * document:
 *
 *   generated by the old template   → DELETE. The rule now produces these dates
 *                                     itself; leaving them makes every week an
 *                                     "edited" week that ignores later changes.
 *   scheduled, rule covers the date → stamp `override`, keeping its own times.
 *   scheduled, rule does NOT cover  → stamp `one-off`. This is the case that
 *                                     matters: without it the gathering vanishes.
 *   cancelled                       → leave completely alone. A cancellation is
 *                                     already exactly the right shape.
 *   in the past                     → leave alone. History, and referenced by
 *                                     statistics and attendance.
 *
 * Then strip `weeksAhead` and `generatedThrough` from the rule, so nothing can
 * read them back and resurrect the generator.
 *
 * USAGE
 * -----
 *   node scripts/migrate-recurrence-to-rule.cjs           # dry run, changes nothing
 *   node scripts/migrate-recurrence-to-rule.cjs --apply   # actually write
 *
 * Idempotent: a second run finds nothing to do. Dry run is the default because
 * this touches the schedule for a whole congregation.
 */

const fs = require('fs');
const path = require('path');

/** Same resolver as scripts/tenancy.cjs — firebase-admin lives in functions/. */
const admin = (() => {
    try {
        return require('firebase-admin');
    } catch (err) {
        if (err.code !== 'MODULE_NOT_FOUND') throw err;
        try {
            return require(require.resolve('firebase-admin', {
                paths: [path.join(__dirname, '..', 'functions', 'node_modules')],
            }));
        } catch {
            console.error('firebase-admin not found. Run `npm install` inside functions/ first.');
            process.exit(1);
        }
    }
})();

const APPLY = process.argv.includes('--apply');

const KEY = process.env.SABHA_ADMIN_KEY
    || path.join(__dirname, '..', 'sabha-ride-app-firebase-adminsdk-fbsvc-dfc82e2f75.json');
if (!fs.existsSync(KEY)) {
    console.error(`Admin SDK key not found at ${KEY}`);
    console.error('Run from the main checkout, or set SABHA_ADMIN_KEY to its path.');
    process.exit(1);
}

admin.initializeApp({ credential: admin.credential.cert(require(KEY)) });
const db = admin.firestore();

/** Mirror of AUDIT_COLLECTION in functions/src/utils/audit.ts. PLURAL. */
const AUDIT_COLLECTION = 'auditLogs';
const CITY_ID = 'boston';
const LOCATION_ID = 'boston-huntington';
const TZ = 'America/New_York';
const RECURRENCE_DOC = 'settings/sabhaRecurrence';

const todayKey = () => new Intl.DateTimeFormat('en-CA', {
    timeZone: TZ, year: 'numeric', month: '2-digit', day: '2-digit',
}).format(new Date());

/** Mirror of dayOfWeekForKey — UTC noon, so no DST edge shifts the weekday. */
function dayOfWeekForKey(dateKey) {
    const [y, m, d] = dateKey.split('-').map(Number);
    return new Date(Date.UTC(y, m - 1, d, 12)).getUTCDay();
}

(async () => {
    console.log(APPLY ? '=== APPLYING ===' : '=== DRY RUN (pass --apply to write) ===');

    const ruleSnap = await db.doc(RECURRENCE_DOC).get();
    const stored = ruleSnap.exists ? ruleSnap.data() : null;

    if (!stored) {
        console.log('No recurring rule is stored. Nothing to migrate against.');
        process.exit(0);
    }

    const days = Array.isArray(stored.daysOfWeek) ? stored.daysOfWeek : [];
    const enabled = stored.enabled === true;
    console.log(`Rule: ${enabled ? 'ON' : 'OFF'} days=[${days}] `
        + `${stored.startTime}–${stored.endTime}`
        + `${stored.weeksAhead ? `  (weeksAhead=${stored.weeksAhead} to strip)` : ''}`
        + `${stored.generatedThrough ? `  (generatedThrough=${stored.generatedThrough} to strip)` : ''}`);

    const today = todayKey();
    console.log(`Today is ${today} (${TZ})\n`);

    const events = await db.collection('events')
        .orderBy(admin.firestore.FieldPath.documentId())
        .get();

    const batch = db.batch();
    let deleted = 0;
    let stampedOverride = 0;
    let stampedOneOff = 0;
    let untouched = 0;

    for (const doc of events.docs) {
        const date = doc.id;
        const e = doc.data();

        if (date < today) {
            untouched++;
            console.log(`  PAST      ${date}  left alone (history)`);
            continue;
        }

        if (e.status === 'cancelled') {
            untouched++;
            console.log(`  CANCELLED ${date}  left alone — already the right shape`);
            continue;
        }

        if (e.fromRecurrence === true) {
            deleted++;
            console.log(`  DELETE    ${date}  generated by the old template`);
            if (APPLY) batch.delete(doc.ref);
            continue;
        }

        if (e.kind === 'override' || e.kind === 'one-off') {
            untouched++;
            console.log(`  DONE      ${date}  already stamped '${e.kind}'`);
            continue;
        }

        // The decision that preserves behaviour. A date the rule covers keeps its
        // own times as an override; a date the rule does NOT cover is a one-off,
        // and without that stamp it would go inert and disappear.
        const covered = enabled && days.includes(dayOfWeekForKey(date));
        const kind = covered ? 'override' : 'one-off';

        if (covered) stampedOverride++; else stampedOneOff++;
        console.log(`  STAMP     ${date}  ${kind}`
            + `  (${e.startTime}–${e.endTime})`
            + (covered ? '' : '  ← would VANISH without this'));

        if (APPLY) batch.update(doc.ref, { kind });
    }

    if (APPLY) {
        batch.update(db.doc(RECURRENCE_DOC), {
            weeksAhead: admin.firestore.FieldValue.delete(),
            generatedThrough: admin.firestore.FieldValue.delete(),
        });
        await batch.commit();

        try {
            await db.collection(AUDIT_COLLECTION).doc().set({
                timestamp: new Date().toISOString(),
                action: 'doc.update',
                actorUid: 'script:migrate-recurrence-to-rule',
                actorName: 'Recurrence model migration',
                targetCollection: 'events',
                targetDocumentId: RECURRENCE_DOC,
                summary: `Migrated the calendar to a rule: deleted ${deleted} generated `
                    + `date(s), stamped ${stampedOverride} override(s) and ${stampedOneOff} one-off(s)`,
                details: { deleted, stampedOverride, stampedOneOff, untouched },
                outcome: 'ok',
                cityId: CITY_ID,
                locationId: LOCATION_ID,
            });
        } catch (auditErr) {
            console.error('  (audit row failed, the migration still applied)', auditErr.message);
        }
    }

    console.log(`\n${APPLY ? 'Deleted' : 'Would delete'} ${deleted} generated date(s).`);
    console.log(`${APPLY ? 'Stamped' : 'Would stamp'} ${stampedOverride} override(s), `
        + `${stampedOneOff} one-off(s).`);
    console.log(`Left ${untouched} document(s) alone.`);
    console.log(`${APPLY ? 'Stripped' : 'Would strip'} weeksAhead and generatedThrough from the rule.`);
    process.exit(0);
})().catch(err => {
    console.error('Failed:', err.message);
    process.exit(1);
});
